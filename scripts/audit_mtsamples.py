"""Lightweight integrity audit of resources/mtsamples.csv (standard library only).

Mirrors load_mtsamples() filtering: transcription word count >= 100 (str.split()).
Writes the findings to docs/citi2026/dataset_audit.md.
"""
import csv
import re
import statistics
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "resources" / "mtsamples.csv"
OUT_PATH = ROOT / "docs" / "citi2026" / "dataset_audit.md"
MIN_WORDS = 100  # same default as load_mtsamples(min_text_length=100)
SEGMENT_WORDS = 100  # size of first/last segment for positional overlap
TOKEN_RE = re.compile(r"[a-z0-9]+")


def tokens(text):
    return set(TOKEN_RE.findall(text.lower()))


def is_blank(value):
    return value is None or value.strip() == ""


def main():
    csv.field_size_limit(2**31 - 1)

    total = 0
    missing_transcription = 0
    missing_description = 0
    eligible = 0
    transcriptions = Counter()
    descriptions = Counter()
    specialties = Counter()
    diag_counts = Counter()  # eligible corpus with non-empty description
    diag_descs = defaultdict(set)

    with open(DATA_PATH, encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            total += 1
            text = row.get("transcription") or ""
            desc = row.get("description") or ""
            if is_blank(text):
                missing_transcription += 1
            if is_blank(desc):
                missing_description += 1
            if len(text.split()) >= MIN_WORDS:
                eligible += 1
                if not is_blank(desc):
                    diag_counts[text] += 1
                    diag_descs[text].add(desc.strip())
            transcriptions[text] += 1
            descriptions[desc.strip()] += 1
            specialties[(row.get("medical_specialty") or "").strip()] += 1

    exact_dup_rows = total - len(transcriptions)
    dup_groups = sum(1 for c in transcriptions.values() if c > 1)
    unique_descriptions = len(descriptions)
    repeated_desc = [(d, c) for d, c in descriptions.most_common() if c > 1]
    desc_repeat_rows = sum(c for _, c in repeated_desc)
    top_specialties = specialties.most_common(5)

    diag_eligible = sum(diag_counts.values())
    diag_unique = len(diag_counts)
    dup_texts = {t: c for t, c in diag_counts.items() if c > 1}
    dup_group_count = len(dup_texts)
    dup_group_records = sum(dup_texts.values())
    dup_excess = dup_group_records - dup_group_count
    multi_desc_groups = sum(1 for t in dup_texts if len(diag_descs[t]) > 1)
    largest_group = max(diag_counts.values(), default=0)

    # Positional lexical overlap: description-token recall of first/last 100 words
    overlap_rows = []
    for text in diag_counts:
        words = text.split()
        if len(words) < 2 * SEGMENT_WORDS:
            continue
        desc_tokens = tokens(min(diag_descs[text]))
        if not desc_tokens:
            continue
        first = len(desc_tokens & tokens(" ".join(words[:SEGMENT_WORDS]))) / len(desc_tokens)
        last = len(desc_tokens & tokens(" ".join(words[-SEGMENT_WORDS:]))) / len(desc_tokens)
        overlap_rows.append((first, last))
    n_overlap = len(overlap_rows)
    first_scores = [f for f, _ in overlap_rows]
    last_scores = [l for _, l in overlap_rows]
    pct_first_higher = 100 * sum(f > l for f, l in overlap_rows) / n_overlap
    pct_equal = 100 * sum(f == l for f, l in overlap_rows) / n_overlap

    lines = [
        "# MTSamples Data Integrity Audit",
        "",
        f"Source: `resources/mtsamples.csv` (generated by `scripts/audit_mtsamples.py`).",
        "",
        "## Counts",
        "",
        f"- Total records: {total}",
        f"- Missing or empty transcription: {missing_transcription}",
        f"- Missing or empty description: {missing_description}",
        f"- Eligible under {MIN_WORDS}-word transcription filter: {eligible}",
        f"- Exact duplicate transcription rows: {exact_dup_rows} (in {dup_groups} duplicate groups)",
        f"- Unique descriptions: {unique_descriptions}",
        f"- Descriptions appearing more than once: {len(repeated_desc)} "
        f"(covering {desc_repeat_rows} records)",
        "",
        "## Most frequent repeated descriptions",
        "",
        "| Count | Description |",
        "|---|---|",
    ]
    for desc, count in repeated_desc[:10]:
        short = desc if len(desc) <= 80 else desc[:77] + "..."
        lines.append(f"| {count} | {short.replace('|', '\\|')} |")

    lines += ["", "## Top 5 medical specialties", "", "| Count | Specialty |", "|---|---|"]
    for spec, count in top_specialties:
        lines.append(f"| {count} | {spec or '(empty)'} |")

    lines += [
        "",
        "## Risks for summarization evaluation",
        "",
        f"- Reference quality: {len(repeated_desc)} descriptions are shared by multiple records, "
        "so the same reference can be paired with different transcriptions.",
        f"- Duplicates: {exact_dup_rows} duplicate transcription rows can inflate effective "
        "sample size and bias bootstrap confidence intervals.",
        "- Eligibility: only documents with at least 100 words are used, which excludes short "
        "notes and may shift results toward long-document behaviour.",
        "- Missing values: loader does not drop empty descriptions; rows with blank "
        "references would score as zero or be silently included.",
        "",
        "## Duplicate analysis on diagnostic eligible corpus",
        "",
        f"Corpus: records with >= {MIN_WORDS} transcription words and a non-empty description.",
        "",
        f"- Eligible records: {diag_eligible}",
        f"- Unique transcriptions: {diag_unique}",
        f"- Records in duplicate-transcription groups: {dup_group_records}",
        f"- Excess duplicate records (beyond first occurrence): {dup_excess}",
        f"- Duplicate-transcription groups: {dup_group_count}",
        f"- Identical transcriptions with more than one distinct description: {multi_desc_groups}",
        f"- Largest duplicate group size: {largest_group}",
        "",
        "## Positional lexical overlap (preliminary diagnostic)",
        "",
        "Not ROUGE and not Lead-3 performance. A lexical diagnostic only.",
        "",
        f"Corpus: unique transcriptions from the diagnostic eligible corpus with >= {2 * SEGMENT_WORDS} words.",
        f"Tokenisation: lowercase, ASCII alphanumeric runs (`[a-z0-9]+`), no stopword removal.",
        f"Measure: recall = |unique description tokens found in segment| / |unique description tokens|.",
        f"Segments: first and last {SEGMENT_WORDS} whitespace-separated words of the transcription.",
        "",
        f"- Unique documents analysed: {n_overlap}",
        f"- First {SEGMENT_WORDS} words: mean {statistics.mean(first_scores):.4f}, median {statistics.median(first_scores):.4f}",
        f"- Last {SEGMENT_WORDS} words: mean {statistics.mean(last_scores):.4f}, median {statistics.median(last_scores):.4f}",
        f"- First segment higher overlap: {pct_first_higher:.1f}% of documents",
        f"- Equal overlap: {pct_equal:.1f}% of documents",
        "",
    ]

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")

    print(f"total={total} missing_tx={missing_transcription} missing_desc={missing_description} "
          f"eligible={eligible} dup_rows={exact_dup_rows} unique_desc={unique_descriptions}")
    print(f"written: {OUT_PATH}")


if __name__ == "__main__":
    main()
